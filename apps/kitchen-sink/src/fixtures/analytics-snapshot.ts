function day(offset: number): { readonly timestamp: number; readonly date: string } {
	const date = new Date();
	date.setUTCDate(date.getUTCDate() - offset);
	return { timestamp: date.getTime(), date: date.toISOString().slice(0, 10) };
}

function activity(multiplier = 1): AnalyticsSnapshot["activity"] {
	return Array.from({ length: 30 }, (_, index) => {
		const date = day(29 - index);
		const wave = index % 6;
		const requests = Math.round((wave + 1) * multiplier);
		return {
			...date,
			messages: requests * 3,
			requests,
			errors: wave === 5 ? 1 : 0,
			tokens: requests * 28000,
			cost: requests * 0.18,
			level: Math.min(4, Math.ceil((wave + 1) / 1.5)),
		};
	});
}

